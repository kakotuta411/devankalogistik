    public static function code128(string $text): string
    {
        $text = strtoupper($text);
        $checksum = 104; // Start B
        $code = [104]; // Start B
        $pos = 1;

        foreach (str_split($text) as $char) {
            $val = self::$code128B[$char] ?? 0;
            $code[] = $val + 32;
            $checksum += ($val + 32) * $pos;
            $pos++;
        }

        $checksum = $checksum % 103;
        $code[] = $checksum;
        $code[] = 105; // Stop

        // Build pattern
        $pattern = '';
        foreach ($code as $c) {
            $pattern .= self::$patterns[$c] ?? '11000111010';
        }

        // Render
        $barWidth = 2;
        $quietZone = 10;
        $imgWidth = strlen($pattern) * $barWidth + $quietZone * 2;
        $imgHeight = 60;
        $img = imagecreate($imgWidth, $imgHeight);
        $white = imagecolorallocate($img, 255, 255, 255);
        $black = imagecolorallocate($img, 0, 0, 0);
        imagefill($img, 0, 0, $white);

        $x = $quietZone;
        foreach (str_split($pattern) as $bit) {
            if ($bit === '1') {
                imagefilledrectangle($img, $x, 0, $x + $barWidth - 1, $imgHeight - 1, $black);
            }
            $x += $barWidth;
        }

        // Add text below
        // imagestring($img, 3, (int)(($imgWidth - strlen($text) * 7) / 2), $imgHeight - 15, $text, $black);

        ob_start();
        imagepng($img);
        $pngData = ob_get_clean();
        imagedestroy($img);

        return 'data:image/png;base64,' . base64_encode($pngData);
    }
